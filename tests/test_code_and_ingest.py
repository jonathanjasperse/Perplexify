CPP_WITH_MACROS = """#pragma once

namespace juce
{

/** Base class for audio processors. */
class JUCE_API AudioProcessor
{
public:
    /** Renders the next block. */
    virtual void processBlock (AudioBuffer<float>& buffer, MidiBuffer& midi) = 0;

    /** Called before playback starts. */
    virtual void prepareToPlay (double sampleRate, int blockSize) = 0;

    JUCE_DECLARE_NON_COPYABLE (AudioProcessor)
};

} // namespace juce
"""


def write(root: Path, rel: str, text: str) -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, "utf-8")
    return p


class CodeLoader(TempHome):
    def test_cpp_with_export_macros_keeps_structure_and_original_text(self):
        p = write(Path(self._home), "AudioProcessor.h", CPP_WITH_MACROS)
        doc = load_code(p, "src/AudioProcessor.h")
        self.assertEqual((doc.kind, doc.lang, doc.title), ("code", "cpp", "src/AudioProcessor.h"))
        chunks = chunk_document(doc)
        text = "\n".join(c.text for c in chunks)
        self.assertIn("JUCE_API AudioProcessor", text)                       # stored text is the original, not the parser's view
        self.assertNotIn("JUCE_DECLARE_NON_COPYABLE (AudioProcessor);", text)  # the helper semicolon never leaks
        heads = " ".join(c.heading for c in chunks)
        self.assertIn("processBlock", heads)
        self.assertIn("prepareToPlay", heads)
        self.assertTrue(all((c.anchor or "").startswith("L") for c in chunks))

    def test_line_ranges_point_at_the_real_lines(self):
        p = write(Path(self._home), "lines.py", "import os\n\n\ndef first():\n    return 1\n\n\ndef second():\n    return 2\n" * 1)
        chunks = chunk_document(load_code(p, "lines.py"))
        lines = p.read_text("utf-8").split("\n")
        for c in chunks:
            a, b = (int(x) for x in (c.anchor[1:].split("-L") + [c.anchor[1:]])[:2]) if "-L" in c.anchor else (int(c.anchor[1:]),) * 2
            self.assertEqual("\n".join(lines[a - 1:b]).strip(), c.text.strip())

    def test_big_classes_are_opened_into_members(self):
        body = "".join(f"    def method{i}(self):\n        '''Doc {i}.'''\n        return {i} * 2\n\n" for i in range(60))
        p = write(Path(self._home), "big.py", "class Big:\n" + body)
        heads = [c.heading for c in chunk_document(load_code(p, "big.py"))]
        self.assertGreater(len(heads), 2)
        self.assertTrue(all("Big" in h for h in heads))

    def test_secrets_are_redacted_and_generated_or_minified_files_skipped(self):
        p = write(Path(self._home), "cfg.py", 'KEY = "AKIAABCDEFGHIJKLMNOP"\npassword = "correct-horse-battery"\nx = 1\n')
        doc = load_code(p, "cfg.py")
        self.assertEqual(doc.redactions, 2)
        joined = " ".join(c.text for c in chunk_document(doc))
        self.assertNotIn("AKIA", joined)
        self.assertNotIn("correct-horse", joined)
        self.assertIsNone(load_code(write(Path(self._home), "gen.js", "// Code generated by protoc. DO NOT EDIT.\nvar a = 1;\n"), "gen.js"))
        self.assertIsNone(load_code(write(Path(self._home), "min.js", "var a=" + "1+" * 3000 + "1;"), "min.js"))
        binfile = Path(self._home) / "blob.cpp"
        binfile.write_bytes(b"\x00\x01\x02" * 100)
        self.assertIsNone(load_code(binfile, "blob.cpp"))

    def test_markdown_in_a_repo_is_titled_by_path_and_redacted(self):
        p = write(Path(self._home), "README.md", "# Title\n\nUse token = \"ghp_abcdefghijklmnopqrstuvwxyz0123456789\" to log in.\n")
        doc = load_file(p, "docs/README.md")
        self.assertEqual(doc.title, "docs/README.md")
        self.assertEqual(doc.redactions, 1)


class RepoScanning(TempHome):
    def make_repo(self) -> Path:
        root = Path(self._home) / "repo"
        write(root, "src/app.py", "def run():\n    return 1\n")
        write(root, "src/ignored.py", "x = 1\n")
        write(root, ".gitignore", "ignored.py\nbuild_out/\n")
        write(root, "build_out/gen.py", "y = 2\n")
        write(root, "node_modules/lib/index.js", "module.exports = 1\n")
        write(root, ".env", "SECRET=1\n")
        write(root, "id_rsa", "-----BEGIN RSA PRIVATE KEY-----\nabc\n-----END RSA PRIVATE KEY-----\n")
        write(root, "package-lock.json", "{}")
        write(root, "docs/guide.md", "# Guide\n\nHello there, this is the guide.\n")
        write(root, "CMakeLists.txt", "project(Demo)\nadd_library(Demo a.cpp)\n")
        write(root, "image.png", "not really an image")
        write(root, "sub/.gitignore", "local.py\n")
        write(root, "sub/local.py", "z = 3\n")
        write(root, "sub/keep.py", "w = 4\n")
        return root

    def scan(self, root, **kw):
        return scan_repo(root, RepoOptions(**kw), uri_for=lambda r: "u://" + r, origin="external", stored_for=lambda r: r)

    def test_gitignore_vendored_secret_and_lock_files(self):
        root = self.make_repo()
        scan = self.scan(root)
        got = sorted(c.rel for c in scan.candidates)
        self.assertEqual(got, ["CMakeLists.txt", "docs/guide.md", "src/app.py", "sub/keep.py"])
        self.assertEqual(sorted(scan.secret_files), [".env", "id_rsa"])

    def test_include_exclude_and_docs_toggle(self):
        root = self.make_repo()
        self.assertEqual([c.rel for c in self.scan(root, include=["src/"]).candidates], ["src/app.py"])
        self.assertNotIn("sub/keep.py", [c.rel for c in self.scan(root, exclude=["sub/"]).candidates])
        self.assertNotIn("docs/guide.md", [c.rel for c in self.scan(root, include_docs=False).candidates])
        self.assertIn("src/ignored.py", [c.rel for c in self.scan(root, use_gitignore=False).candidates])

    def test_cmakelists_is_code_not_a_text_document(self):
        doc = load_file(write(Path(self._home), "cm/CMakeLists.txt", "project(Demo)\n"), "CMakeLists.txt")
        self.assertEqual(doc.lang, "cmake")


class RepoIndexing(TempHome):
    def test_import_rerun_edit_and_prune(self):
        from perplexify.context import AppContext

        ctx = AppContext()
        lib = ctx.libs.create("Repo test")
        root = Path(self._home) / "indexrepo"
        write(root, "a.py", "def alpha():\n    return 'a'\n")
        write(root, "b.py", "def beta():\n    return 'b'\n")
        job = Job("t", "t", lib.id)
        kw = dict(uri_for=lambda r: "u://" + r, origin="external", stored_for=lambda r: str(root / r), uri_prefix="u://")
        s1, _ = ingest.index_repo(lib, root, job, RepoOptions(), **kw)
        self.assertEqual((s1.indexed, lib.store.stats()["kinds"]), (2, {"code": 2}))
        s2, _ = ingest.index_repo(lib, root, job, RepoOptions(), **kw)
        self.assertEqual((s2.indexed, s2.unchanged), (0, 2))
        time.sleep(0.05)
        (root / "a.py").write_text("def alpha():\n    return 'changed'\n", "utf-8")
        (root / "b.py").unlink()
        s3, _ = ingest.index_repo(lib, root, job, RepoOptions(), **kw)
        self.assertEqual(s3.indexed, 1)
        titles = [r["title"] for r in lib.store.iter_documents()]
        self.assertEqual(titles, ["a.py"])  # b.py was deleted upstream and is pruned
        self.assertEqual(lib.store.stats()["documents"], 1)


class PureHelpers(unittest.TestCase):
    def test_parse_github(self):
        for text, expect in [
            ("https://github.com/juce-framework/JUCE", ("juce-framework", "JUCE", None)),
            ("https://github.com/juce-framework/JUCE.git", ("juce-framework", "JUCE", None)),
            ("github.com/a/b/tree/develop/src", ("a", "b", "develop")),
            ("git@github.com:a/b.git", ("a", "b", None)),
            ("a/b", ("a", "b", None)),
        ]:
            r = parse_github(text)
            self.assertEqual((r.owner, r.repo, r.ref), expect, text)
        self.assertEqual(parse_github("a/b", ref="v1").ref, "v1")
        self.assertIsNone(parse_github("https://gitlab.com/a/b"))
        self.assertEqual(parse_github("a/b", ref="main").blob_url("x y/z.cpp"), "https://github.com/a/b/blob/main/x%20y/z.cpp")

    def test_crawler_url_helpers(self):
        self.assertEqual(normalize_url("HTTPS://Docs.JUCE.com:443/master/a/../index.html#top"), "https://docs.juce.com/master/index.html")
        self.assertIsNone(normalize_url("mailto:x@y.z"))
        self.assertEqual(url_to_relpath("https://docs.juce.com/master/"), "docs.juce.com/master/index.html")
        self.assertEqual(url_to_relpath("https://h.com/a/b", "text/html"), "h.com/a/b.html")
        rel = url_to_relpath("https://h.com/s?q=1")
        self.assertTrue(rel.startswith("h.com/s_q") and rel.endswith(".html") is False or "_q" in rel)
        bad = url_to_relpath('https://h.com/a:b/"c"?.html')
        self.assertFalse(any(ch in bad for ch in '<>:"|?*'))

    def test_link_extraction(self):
        html = (b'<base href="https://d.com/x/"><a href="a.html#s">A</a><a href=\'b.html\'>B</a><a href="mailto:z@z">M</a>'
                b'<link rel="stylesheet" href="s.css"><link rel="icon" href="f.ico"><script src="j.js"></script>'
                b'<img src="i.png"><a href="javascript:void(0)">x</a><a href="&amp;q=1">y</a>')
        pages, assets = extract_links(html, "https://d.com/x/index.html")
        self.assertIn("https://d.com/x/a.html#s", pages)
        self.assertIn("https://d.com/x/b.html", pages)
        self.assertEqual(sorted(a.rsplit("/", 1)[1] for a in assets), ["f.ico", "i.png", "j.js", "s.css"])
        self.assertFalse(any(p.startswith(("mailto", "javascript")) for p in pages))

    def test_excerpts_show_code_with_path_lines_and_language(self):
        code = Hit("l", "Lib", 1, 1, "src/foo.cpp", "u", "src/foo.cpp > ns > Foo::bar", "L12-L20", "int bar() { return 1; }",
                   "external", "p", "code", lang="cpp")
        doc = Hit("l", "Lib", 2, 2, "Guide", "u", "Guide > Install", None, "Run the installer.", "mirror", "p", "html")
        text, used = build_excerpts([code, doc], 5000)
        self.assertIn("[1] src/foo.cpp:12-20  (ns > Foo::bar)\n```cpp\nint bar() { return 1; }\n```", text)
        self.assertIn("[2] Guide > Install\nRun the installer.", text)
        self.assertEqual(len(used), 2)
        self.assertEqual((line_range("L5"), line_range("L5-L9"), line_range("page=3"), line_range(None)), ("5", "5-9", "", ""))

    def test_excerpt_budget_truncates_instead_of_overflowing(self):
        big = Hit("l", "Lib", 1, 1, "t", "u", "t > h", None, "word " * 4000, "mirror", "p", "html")
        text, used = build_excerpts([big, big], 600)
        self.assertEqual(len(used), 1)
        self.assertLess(len(text), 600 * 4)


