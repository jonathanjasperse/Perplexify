"""Source code -> ParsedDoc.

Files are cut along the code's own structure with tree-sitter: each function, method or class becomes a
passage (a doc comment stays attached to the thing it documents), small neighbours are packed together,
and classes / namespaces too big for one passage are opened up so their members are searchable on their
own. Every passage knows its exact line range, so answers can cite `path:120-148`. Languages without a
grammar, config files and anything that fails to parse fall back to line windows.
"""
from __future__ import annotations

import importlib
import re
import threading
from dataclasses import dataclass
from pathlib import Path

from ..chunking import ParsedDoc, Section
from ..secretscan import redact
from ..textutil import decode_bytes

MAX_CODE_BYTES = 600_000
TARGET = 1400     # characters per passage we aim for
MAX_CHUNK = 2400  # anything bigger is split by lines
OWN = 450         # members at least this big become a passage of their own; smaller ones are packed together

